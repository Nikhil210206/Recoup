"""The whole evaluation, in one reproducible command.

    make eval

Runs every comparison this project makes, in order, from the same fixed seed,
and writes `EVALUATION.md` from the results so the document cannot drift from
the numbers it reports.

The order is deliberate. It moves from the largest claim to the smallest, and
ends with the two robustness sweeps, because a result is only worth as much as
the conditions under which it survives.

Everything here is a **simulation benchmark**. The one measurement in this
repository that is not simulated is the real Razorpay loop in `docs/evidence/`.
"""

from __future__ import annotations

import argparse
import io
import json
from contextlib import redirect_stdout
from datetime import UTC, datetime
from pathlib import Path

from app.allocator.bake_off import ranked, run_bake_off
from app.allocator.bake_off import render as render_bake_off
from app.allocator.budget import BudgetPolicy
from app.allocator.estimator import AmountOnly, CauseRate, ModelUplift
from app.allocator.policy import Allocator
from app.allocator.siloed import run_siloed
from app.evaluation import BUDGET_FRACTION
from app.evaluation.sweeps import (
    cause_noise_sweep,
    crossover,
    render_cause_sweep,
)
from app.model.levers import compare as compare_levers
from app.model.levers import render as render_levers
from app.model.train import build_frames
from app.simulation.arms import evaluate, load, paired_bootstrap
from app.simulation.generator import WORLDS
from app.simulation.policies import BASELINES, ORACLE, CauseAware

REPO = Path(__file__).resolve().parents[3]


class Report:
    """Collects sections so the console output and the document are identical."""

    def __init__(self) -> None:
        self.sections: list[tuple[str, str]] = []
        #: Structured mirror of the numbers rendered into the sections above.
        #:
        #: The dashboard reads this rather than restating results in markup. A
        #: number typed into a template is a number that can drift from the
        #: harness that produced it, and there is no test that would catch it.
        self.facts: dict = {}

    def add(self, title: str, body: str) -> None:
        self.sections.append((title, body))
        print(f"\n{'─' * 76}\n{title}\n{'─' * 76}")
        print(body)

    def to_markdown(self, meta: dict) -> str:
        head = [
            "# Evaluation",
            "",
            "**Generated by `make eval`. Do not edit by hand.**",
            "",
            "Every number below is a **simulation benchmark**, not production "
            "Razorpay data. The one measurement in this repository that is not "
            "simulated is the real Razorpay loop in [`docs/evidence/`]"
            "(evidence/).",
            "",
            "| | |",
            "|---|---|",
        ]
        head += [f"| {k} | {v} |" for k, v in meta.items()]
        body = [f"\n## {title}\n\n```\n{text}\n```" for title, text in self.sections]
        return "\n".join(head) + "\n" + "\n".join(body) + "\n"


def _capture(fn, *args, **kwargs) -> str:
    buffer = io.StringIO()
    with redirect_stdout(buffer):
        fn(*args, **kwargs)
    return buffer.getvalue().rstrip()


def run(world: str, seed: int) -> tuple[Report, dict]:
    report = Report()
    cases = load(world, seed)
    test = cases[cases.split == "test"].reset_index(drop=True)
    budget = int(len(test) * BUDGET_FRACTION)
    fatigue = WORLDS[world]["fatigue_lambda"]

    meta = {
        "world": f"`{world}` {WORLDS[world]}",
        "seed": seed,
        "cases (test split)": f"{len(test):,}",
        "revenue at risk": f"₹{test.amount_paise.sum() / 100:,.0f}",
        "contact budget": f"{budget:,}",
        "generated": datetime.now(UTC).strftime("%Y-%m-%d"),
    }

    report.facts.update(
        {
            "world": world,
            "seed": seed,
            "budget_fraction": BUDGET_FRACTION,
            "test_cases": int(len(test)),
            "contact_budget": budget,
            "at_risk_rupees": float(test.amount_paise.sum() / 100),
            "generated": meta["generated"],
        }
    )

    # --- 1. the headline: which decision recovers the money -----------------
    levers = compare_levers(test, budget)
    report.facts["levers"] = [
        {
            "lever": r.lever,
            "variant": r.variant,
            "realised_rupees": r.realised_paise / 100,
            "lift": r.lift,
            "contacts": r.contacts,
        }
        for r in levers
    ]
    report.add(
        "1. Which decision recovers the money",
        render_levers(levers)
        + "\n\n"
        + "  'action' holds case selection fixed and varies what we do.\n"
        + "  'ranking' holds the action fixed and varies which cases we work,\n"
        + "  using ORACLE uplift -- the ceiling for ranking, not our estimate.\n\n"
        + "  Ranking is worth ~1% even with perfect knowledge: corr(EV, amount)\n"
        + "  is 0.94, amounts span ~5,000x and uplift ~5x, so the product barely\n"
        + "  reorders. The action choice is worth ~500% because the actions are\n"
        + "  not substitutes.",
    )

    # --- 2. arms under equal budget -----------------------------------------
    estimator = CauseRate().fit(build_frames(world, seed)["train"])

    def allocator(cap: int = 2) -> Allocator:
        return Allocator(
            estimator=estimator,
            budget_policy=BudgetPolicy(max_contacts_per_customer=cap),
        )

    results = run_bake_off(
        test,
        allocator(),
        {
            "B1_razorpay_t3": BASELINES[1],
            "B2_contact_everything": BASELINES[2],
            "B4_cause_aware (arrival)": CauseAware(),
        },
        budget,
        fatigue,
    )
    siloed, silo_stats = run_siloed(test, CauseAware, budget, fatigue_lambda=fatigue)
    pooled = next(
        r.result
        for r in run_bake_off(
            ranked(test),
            allocator(99),
            {"B5_pooled + ranking": CauseAware()},
            budget,
            fatigue,
        )
        if r.result.arm.startswith("B5")
    )
    from app.allocator.bake_off import BudgetedResult

    results.append(BudgetedResult(siloed, budget, siloed.contacts))
    results.append(BudgetedResult(pooled, budget, pooled.contacts))

    report.facts["arms"] = [
        {
            "arm": b.result.arm,
            "incremental_rupees": b.result.incremental_paise / 100,
            "net_rupees": b.result.net_paise / 100,
            "contacts": b.result.contacts,
            "unnecessary_contacts": b.result.unnecessary_contacts,
            "recovered_cases": b.result.recovered_cases,
            "caused_cases": b.result.caused_cases,
            "within_budget": b.within_budget,
        }
        for b in results
    ]
    report.add(
        "2. Every arm under an identical contact budget",
        render_bake_off(results, budget)
        + "\n\n"
        + "  SILOED models the architecture that exists: one agent per loss\n"
        + "  channel, each with its own queue and budget, none aware of the\n"
        + "  others. POOLED+RANKING is an idealised single agent handed a sorted\n"
        + "  queue -- stronger than anything shipping, and included so the\n"
        + "  allocator's advantage is not credited for a mere ORDER BY.\n\n"
        + "  Retries are not rationed: they touch the gateway, not the customer.",
    )

    # --- 3. component ablation ----------------------------------------------
    ablation = [
        ("full (cause-rate estimator, cap 2)", estimator, 2),
        ("no uplift estimate at all", AmountOnly(), 2),
        ("no contact cap", estimator, 99),
    ]
    lines = [f"  {'variant':34}{'incremental Rs':>16}{'contacts':>10}"]
    lines.append("  " + "-" * 60)
    for label, est, cap in ablation:
        result = run_bake_off(
            test,
            Allocator(estimator=est, budget_policy=BudgetPolicy(max_contacts_per_customer=cap)),
            {},
            budget,
            fatigue,
        )[0].result
        lines.append(f"  {label:34}{result.incremental_paise / 100:>16,.0f}{result.contacts:>10,}")
    try:
        import joblib

        model_path = REPO / "artifacts" / f"uplift.{world}.seed{seed}.joblib"
        if model_path.exists():
            result = run_bake_off(
                test,
                Allocator(
                    estimator=ModelUplift(joblib.load(model_path)),
                    budget_policy=BudgetPolicy(max_contacts_per_customer=2),
                ),
                {},
                budget,
                fatigue,
            )[0].result
            lines.append(
                f"  {'per-case ML uplift model':34}"
                f"{result.incremental_paise / 100:>16,.0f}{result.contacts:>10,}"
            )
    except Exception:  # noqa: BLE001 - the ablation is reportable without it
        lines.append("  (per-case model not built; run `make model`)")

    lines += [
        "",
        "  The estimator and the contact cap are worth approximately nothing, and",
        "  are reported that way. A cause-rate group-by tracks true uplift better",
        "  than the fitted per-case model, so the machine learning is not in the",
        "  decision path -- it is retained for forecasting, where calibration",
        "  measurably matters.",
        "",
        "  The cap is kept because it caps how much of one customer's patience a",
        "  merchant may spend across every channel at once. Costing nothing is",
        "  the argument for keeping it, not against it.",
    ]
    report.add("3. What each component is worth", "\n".join(lines))

    # --- 4. significance ----------------------------------------------------
    arm_results = {r.result.arm: r.result for r in results}
    t3 = evaluate(test, BASELINES[1], fatigue)
    sig_lines = [f"  {'arm':34}{'mean diff/case':>16}{'95% CI':>22}{'significant':>13}"]
    sig_lines.append("  " + "-" * 84)
    for name, result in arm_results.items():
        if "t3" in name:
            continue
        stats = paired_bootstrap(result, t3)
        ci = f"[{stats['ci_low_rs']:,.0f}, {stats['ci_high_rs']:,.0f}]"
        sig_lines.append(
            f"  {name:34}{stats['mean_diff_rs']:>+16,.0f}{ci:>22}"
            f"{'yes' if stats['significant'] else 'no':>13}"
        )
    sig_lines += [
        "",
        "  Paired, and valid because every arm faced the same cases with the same",
        "  latent willingness and the same draws. A difference is the policy, not",
        "  the dice.",
    ]
    report.add("4. Paired significance vs Razorpay's T+3", "\n".join(sig_lines))

    # --- 5. ceiling ---------------------------------------------------------
    ceiling = evaluate(test, ORACLE, fatigue)
    ceil_lines = [
        f"  oracle ceiling (reads ground truth): Rs {ceiling.incremental_paise / 100:,.0f}",
        "",
        f"  {'arm':34}{'% of ceiling':>14}",
        "  " + "-" * 48,
    ]
    for name, result in sorted(arm_results.items(), key=lambda kv: -kv[1].incremental_paise):
        pct = 100 * result.incremental_paise / max(ceiling.incremental_paise, 1)
        ceil_lines.append(f"  {name:34}{pct:>13.1f}%")
    ceil_lines += [
        "",
        "  An upper bound under the same action budget, never ranked against the",
        "  arms. Without it, '25% of revenue at risk' is uninterpretable -- much",
        "  of that risk is structurally unrecoverable or would self-recover.",
    ]
    report.add("5. How much was left to take", "\n".join(ceil_lines))

    # --- 6. sweep A: a wrong world -----------------------------------------
    world_lines = [
        f"  {'world':16}{'action lever':>15}{'ranking lever':>16}{'allocator vs arrival':>22}"
    ]
    world_lines.append("  " + "-" * 70)
    for name in WORLDS:
        w_cases = load(name, seed)
        w_test = w_cases[w_cases.split == "test"].reset_index(drop=True)
        w_budget = int(len(w_test) * BUDGET_FRACTION)
        w_fatigue = WORLDS[name]["fatigue_lambda"]
        levers = compare_levers(w_test, w_budget)
        action = max(r.lift for r in levers if r.lever == "action")
        rank = max(r.lift for r in levers if r.lever == "ranking")

        w_est = CauseRate().fit(build_frames(name, seed)["train"])
        w_results = run_bake_off(
            w_test,
            Allocator(estimator=w_est, budget_policy=BudgetPolicy(max_contacts_per_customer=2)),
            {"arrival": CauseAware()},
            w_budget,
            w_fatigue,
        )
        alloc = next(r.result for r in w_results if r.result.arm == "RECOUP_allocator")
        arrival = next(r.result for r in w_results if r.result.arm == "arrival")
        delta = (alloc.incremental_paise - arrival.incremental_paise) / max(
            arrival.incremental_paise, 1
        )
        world_lines.append(f"  {name:16}{action:>+14.0%}{rank:>+15.1%}{delta:>+21.1%}")
    world_lines += [
        "",
        "  Worlds hold the SAME failures and vary only how recoverable they are,",
        "  so any difference is attributable to the world and nothing else.",
    ]
    report.add("6. Sweep A -- does it survive a different world?", "\n".join(world_lines))

    # --- 7. sweep B: a wrong cause -----------------------------------------
    points, baselines = cause_noise_sweep(test, budget, seed=seed)
    report.add(
        "7. Sweep B -- does it survive a wrong cause?",
        render_cause_sweep(points, baselines)
        + "\n\n"
        + "  The system never receives a cause; it derives one from Razorpay's\n"
        + "  error fields. So the corruption rewrites the error CODE, which\n"
        + "  exercises the same lookup the live path uses.\n\n"
        + "  Plans are made on corrupted input and scored against the true latent\n"
        + "  parameters -- which is what a misclassification costs in production:\n"
        + "  you act on what you believed, and reality settles on what was true.",
    )

    # --- 8. how often the gates refused ------------------------------------
    #
    # "Zero policy violations" is true by construction and proves nothing. What
    # shows a gate is load-bearing is how often it refused, and what that cost.
    #
    # The split below is the entire point of this section. An earlier cut of
    # this number reported every non-acted case as a refusal -- 507 cases and
    # Rs 481,799 on the base world -- which folds two unrelated things together:
    #
    #   governance   a rule declined this case on principle. It would still
    #                decline it with unlimited budget.
    #   exhaustion   the allocator simply ran out of contacts. Nothing refused
    #                anything; the money ran out.
    #
    # Reporting the total would be a plausible number, in a believable range,
    # under a correct-sounding label, measuring something other than what the
    # label says. Keep the two lines apart.
    gate = allocator()
    gate.budget_policy.max_total_contacts = budget
    gate_decisions, _ = gate.plan(test)
    amount_by_case = dict(zip(test.case_id, test.amount_paise, strict=True))

    EXHAUSTED = "global_budget_exhausted"
    tally: dict[tuple[str, str], list[int]] = {}
    for d in gate_decisions:
        if d.acted:
            continue
        entry = tally.setdefault((d.reason, d.rule), [0, 0])
        entry[0] += 1
        entry[1] += amount_by_case.get(d.case_id, 0)

    governance = sorted(
        ((r, k, n, p) for (r, k), (n, p) in tally.items() if r != EXHAUSTED),
        key=lambda row: -row[2],
    )
    exhausted = [(r, k, n, p) for (r, k), (n, p) in tally.items() if r == EXHAUSTED]

    acted = sum(1 for d in gate_decisions if d.acted)
    gov_cases = sum(row[2] for row in governance)
    gov_paise = sum(row[3] for row in governance)

    planned_contacts = sum(1 for d in gate_decisions if d.acted and d.uses_contact)
    gate_lines = [
        f"  {len(gate_decisions):,} cases planned; {acted:,} acted on, of which",
        f"  {planned_contacts:,} would spend a contact against a budget of {budget:,}.",
        "",
        "  These are PLANNING decisions. Section 2 reports a lower contact count",
        "  for the same arm because that one is measured after execution, where",
        "  fatigue and collision drop some of what was planned. Both are correct;",
        "  they are different stages, and a refusal happens at this one.",
        "",
        f"  {'reason':40}{'rule':20}{'cases':>7}{'Rs refused':>13}",
        "  " + "-" * 80,
    ]
    for reason, rule, n, paise in governance:
        gate_lines.append(f"  {reason:40}{rule:20}{n:>7,}{paise / 100:>13,.0f}")
    gate_lines.append("  " + "-" * 80)
    gate_lines.append(f"  {'GOVERNANCE REFUSALS':60}{gov_cases:>7,}{gov_paise / 100:>13,.0f}")
    gate_lines.append("")
    for reason, rule, n, paise in exhausted:
        gate_lines.append(f"  {reason:40}{rule:20}{n:>7,}{paise / 100:>13,.0f}")

    gate_lines += [
        "",
        "  The two blocks are NOT summed, and must not be. A governance refusal",
        "  would still refuse with unlimited budget: no customer action can fix",
        "  the failure, or the expected value does not clear the floor. Budget",
        "  exhaustion is not a gate firing at all -- it is the contact budget",
        "  running out, and it moves with the budget rather than with policy.",
        "",
        "  Adding them yields a larger, better-sounding figure that measures",
        "  neither quantity. The governance line is the one that answers 'is the",
        "  gate load-bearing', and it is the one the README quotes.",
    ]
    report.facts["refusals"] = {
        "planned": len(gate_decisions),
        "acted": acted,
        "governance": [
            {"reason": r, "rule": k, "cases": n, "rupees": paise / 100}
            for r, k, n, paise in governance
        ],
        "governance_cases": gov_cases,
        "governance_rupees": gov_paise / 100,
        "budget_exhausted": [
            {"reason": r, "rule": k, "cases": n, "rupees": paise / 100}
            for r, k, n, paise in exhausted
        ],
    }
    report.add("8. How often the gates refused", "\n".join(gate_lines))

    meta["cause-error crossover"] = (
        f"{crossover(points):.0%}" if crossover(points) is not None else "none observed"
    )
    return report, meta


def main() -> None:
    parser = argparse.ArgumentParser(description="Run the full evaluation.")
    parser.add_argument("--world", choices=sorted(WORLDS), default="base")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--write", action="store_true", help="write EVALUATION.md")
    args = parser.parse_args()

    print("Recoup -- full evaluation")
    print(f"  world : {args.world}")
    print(f"  seed  : {args.seed}")
    print("  SIMULATION BENCHMARK -- not production Razorpay data")

    report, meta = run(args.world, args.seed)

    if args.write:
        path = REPO / "EVALUATION.md"
        path.write_text(report.to_markdown(meta))
        print(f"\nwrote {path.relative_to(REPO)}")

        # The same numbers, machine-readable, for anything that renders them.
        # Written from the identical run, so the dashboard and the document
        # cannot disagree about what the experiment found.
        sidecar = REPO / "docs" / "evidence" / "evaluation.json"
        sidecar.write_text(json.dumps(report.facts, indent=2, sort_keys=True) + "\n")
        print(f"wrote {sidecar.relative_to(REPO)}")


if __name__ == "__main__":
    main()
