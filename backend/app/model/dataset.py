"""Training data from a randomised exploration policy.

## Why randomise

A model trained on logs from a policy learns that policy's blind spots. If the
existing system only ever sends payment links at 24 hours, the data contains no
evidence about 2 hours, and the model will confidently extrapolate into a region
it has never seen. Worse, action choice correlates with case characteristics --
the policy sends links to promising cases -- so "cases that got a link recovered
more" conflates the treatment with the selection.

So the training set is generated by an explicitly randomised policy: action and
timing drawn at random, with a control arm that does nothing at all. That is a
randomised trial, and it is also how you would actually bootstrap this in
production -- a holdback group is standard practice in recovery products for
exactly this reason.

## Why two arms

The control arm gives `P(recover | no action)`. The treatment arm gives
`P(recover | action, timing)`. Their difference is the uplift, and uplift is the
quantity the allocator needs: not "will this recover" but "will this recover
*because of us*".

Both targets are observable in production. Neither requires the counterfactual.
That matters -- a model trained on `caused_by_us` would be untrainable outside a
simulator, and a system that only works in simulation is not a system.

## What is deliberately not randomised

Suppression rules. The explorer never contacts a case whose cause forbids it --
a fraud block, or a merchant-configuration failure no customer action can fix.
Those are policy, not hypotheses to test, and a real holdback group would respect
them too.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np
import pandas as pd

from app import taxonomy
from app.model import features as feat
from app.simulation import assumptions as A
from app.simulation.episode import run_episode
from app.simulation.outcomes import ActionType
from app.simulation.policies import observable_cause

#: Share of cases assigned to the control arm. Large enough to fit a baseline
#: model, small enough that most of the sample is still learning about actions.
CONTROL_SHARE = 0.25

#: Actions the explorer may take. `merchant_alert` and `human_review` are
#: excluded: the first has no customer-facing effect to learn, the second is an
#: escalation decision rather than a recovery treatment.
EXPLORE_ACTIONS = [
    ActionType.RETRY,
    ActionType.PAYMENT_LINK_WHATSAPP,
    ActionType.PAYMENT_LINK_SMS,
    ActionType.PAYMENT_LINK_EMAIL,
    ActionType.METHOD_SWITCH_PROMPT,
]

#: Delay grid, log-spaced from minutes to three days. Uniform spacing would put
#: almost all the mass past the point where fast-decaying causes are recoverable.
DELAY_GRID_H = np.array([0.05, 0.25, 1.0, 3.0, 8.0, 24.0, 48.0, 72.0])


@dataclass
class RandomExplorer:
    """One randomly chosen action at a randomly chosen time, or nothing."""

    seed: int = 0
    name: str = "explorer"

    def __post_init__(self):
        self._rng = np.random.default_rng(self.seed)

    def plan(self, case) -> tuple[ActionType | None, float]:
        cause_key = observable_cause(case)
        cause = taxonomy.get(cause_key) if cause_key else None

        if self._rng.random() < CONTROL_SHARE:
            return None, 0.0

        allowed = list(EXPLORE_ACTIONS)
        if cause is not None:
            if not cause.contact_ok:
                # Never message a customer about a fraud block or a merchant
                # setting. Not a hypothesis worth testing.
                allowed = [ActionType.RETRY]
            if cause.retry_policy == taxonomy.RetryPolicy.NEVER:
                return None, 0.0
        if str(case.get("channel") or "") == "abandoned_checkout":
            # No payment exists to re-attempt.
            allowed = [a for a in allowed if a != ActionType.RETRY] or [
                ActionType.PAYMENT_LINK_SMS
            ]

        action = allowed[int(self._rng.integers(0, len(allowed)))]
        delay = float(self._rng.choice(DELAY_GRID_H))
        return action, delay


class _FixedPlan:
    """Adapter turning one (action, delay) decision into a single-step policy."""

    name = "explorer"

    def __init__(self, action: ActionType | None, delay_h: float):
        self.action = action
        self.delay_h = delay_h

    def next_action(self, case, history):
        if history or self.action is None:
            return None
        return self.action, self.delay_h


def build_training_frame(cases: pd.DataFrame, seed: int = 0) -> pd.DataFrame:
    """Run the explorer over `cases` and return one labelled row each.

    The label is `recovered` -- whether money arrived inside the window. That is
    what production observes. It is deliberately *not* `caused_by_us`: the
    counterfactual exists here but would not exist in a real deployment, and a
    model that cannot be retrained on real data is a demo.
    """
    explorer = RandomExplorer(seed=seed)

    plans = [explorer.plan(row) for _, row in cases.iterrows()]
    episodes = [
        run_episode(row, _FixedPlan(action, delay))
        for (action, delay), (_, row) in zip(plans, cases.iterrows(), strict=True)
    ]

    frame = feat.build(cases)
    frame["action"] = [str(a) if a is not None else "none" for a, _ in plans]
    frame["log_delay_h"] = np.log1p([d for _, d in plans])
    frame["prior_contacts"] = 0.0

    frame["treated"] = [a is not None for a, _ in plans]
    frame["recovered"] = [e.recovered for e in episodes]
    frame["amount_paise"] = cases["amount_paise"].to_numpy()
    frame["case_id"] = cases["case_id"].to_numpy()

    # Retained for evaluation only. Never a feature, never a target -- it is the
    # counterfactual the model is not allowed to see and the allocator is scored
    # against.
    frame["_truth_caused"] = [e.caused_by_us for e in episodes]
    return frame


def split_arms(frame: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """(control, treatment)."""
    return frame[~frame.treated].copy(), frame[frame.treated].copy()


def summarise(frame: pd.DataFrame) -> dict:
    control, treated = split_arms(frame)
    return {
        "n": len(frame),
        "control_n": len(control),
        "treated_n": len(treated),
        "control_recovery_rate": float(control.recovered.mean()) if len(control) else 0.0,
        "treated_recovery_rate": float(treated.recovered.mean()) if len(treated) else 0.0,
        "actions": {k: int(v) for k, v in frame.action.value_counts().items()},
        "fatigue_lambda": A.CONTACT_FATIGUE_LAMBDA.value,
    }
